/**
 * Creates an isolated experience-level snapshot of a library question template.
 * Mutating this snapshot will NEVER affect the original template in the library.
 */
export function createExperienceQuestionSnapshot(template: Question): Question {
  const instanceId = `q-inst-${Date.now()}-${Math.random().toString(36).substring(2, 7)}`;
  return {
    ...JSON.parse(JSON.stringify(template)),
    id: instanceId,
    questionInstanceId: instanceId,
    sourceTemplateId: template.sourceTemplateId || template.id,
    enabled: template.enabled !== false,
    required: template.required !== false,
  };
}

